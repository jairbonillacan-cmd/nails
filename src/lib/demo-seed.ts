function isoAtOffset(daysFromToday: number, hourLocal: number, minuteLocal = 0): string {
  const now = new Date();
  const baseKey = getDateKeyInTimezone(now, 'America/Mexico_City');
  const [y = 2026, m = 1, d = 1] = baseKey.split('-').map(Number);
  const utcMs = Date.UTC(y, m - 1, d + daysFromToday, hourLocal + 6, minuteLocal, 0, 0);
  return new Date(utcMs).toISOString();
}

function dateKeyAtOffset(daysFromToday: number): string {
  const now = new Date();
  const baseKey = getDateKeyInTimezone(now, 'America/Mexico_City');
  const [y = 2026, m = 1, d = 1] = baseKey.split('-').map(Number);
  const dt = new Date(Date.UTC(y, m - 1, d + daysFromToday, 12, 0, 0));
  return dt.toISOString().slice(0, 10);
}

